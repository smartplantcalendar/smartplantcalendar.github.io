/**
 * Generates supabase/seed.sql from the TypeScript seed data so the database
 * and the preview mode always start from the same content.
 * Run: npm run db:seed:generate
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { SEED_CROPS } from "../src/data/crops";
import { SEED_FAQS } from "../src/data/faqs";
import { COUNTRIES, REGIONS } from "../src/data/regions";
import { DEFAULT_THRESHOLDS } from "../src/domain/weather";

const q = (v: string | null | undefined) => (v == null || v === "" ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const arr = (v: (string | number)[] | undefined, type: "text" | "int") =>
  !v || v.length === 0 ? `'{}'::${type}[]` : `array[${v.map((x) => (type === "text" ? q(String(x)) : String(x))).join(",")}]::${type}[]`;

/**
 * A seeded crop that is still "incomplete" and was never edited by an admin
 * (updated_by is null) takes the new documented data; anything else is left
 * exactly as it is.
 */
const UPGRADE =
  "public.crops.data_status = 'incomplete' and public.crops.updated_by is null and excluded.data_status <> 'incomplete'";

/** A crop no administrator has edited: generated estimates may be refreshed. */
const UNEDITED = "public.crops.updated_by is null";
const ESTIMATE_COLUMNS = ["estimate_dataset", "estimate_harvest_meaning", "estimate_note", "estimate_links", "estimate_review_notes"];

const lines: string[] = [
  "-- Generated by scripts/generate-seed.ts — do not edit by hand.",
  "-- Preliminary content: review with a local agronomist before relying on it.",
  "begin;",
  "",
];

COUNTRIES.forEach((c, i) => {
  lines.push(`insert into public.countries (code, name, sort_order) values (${q(c.code)}, ${q(c.name)}, ${i}) on conflict (code) do update set name = excluded.name;`);
});
lines.push("");
REGIONS.forEach((r, i) => {
  lines.push(
    `insert into public.regions (id, country_code, name, zone, latitude, longitude, timezone, sort_order) values (${q(r.id)}, ${q(r.countryCode)}, ${q(r.name)}, ${q(r.zone)}, ${r.latitude}, ${r.longitude}, ${q(r.timezone)}, ${i}) on conflict (id) do nothing;`,
  );
});
lines.push("");

for (const c of SEED_CROPS) {
  lines.push(`-- ${c.slug}`);
  // New crops are inserted; existing rows keep every admin edit and only gain
  // new search aliases (merged, never removed or duplicated) and, when still
  // empty, the propagation list.
  lines.push(
    `insert into public.crops (slug, name, other_names, scientific_name, category, life_cycle, difficulty, sun, water, frost_sensitive, space_types, growth_days_min, growth_days_max, growth_note, summary, watering_summary, image_alt, data_status, source_note, propagation, primary_method, flowering_note, harvest_note, first_yield_note, estimate_dataset, estimate_harvest_meaning, estimate_note, estimate_links, estimate_review_notes) values (${q(c.slug)}, ${q(c.name)}, ${arr(c.otherNames, "text")}, ${q(c.scientificName)}, ${q(c.category)}, ${q(c.lifeCycle)}, ${q(c.difficulty)}, ${q(c.sun)}, ${q(c.water)}, ${c.frostSensitive}, ${arr(c.spaceTypes, "text")}, ${n(c.growthDaysMin)}, ${n(c.growthDaysMax)}, ${q(c.growthNote)}, ${q(c.summary)}, ${q(c.wateringSummary)}, ${q(c.imageAlt)}, ${q(c.dataStatus)}, ${q(c.sourceNote)}, ${arr(c.propagation, "text")}, ${q(c.primaryMethod)}, ${q(c.floweringNote)}, ${q(c.harvestNote)}, ${q(c.firstYieldNote)}, ${q(c.estimate?.dataset)}, ${q(c.estimate?.harvestMeaning)}, ${q(c.estimate?.note)}, ${arr(c.estimate?.contextUrls, "text")}, ${arr(c.estimate?.reviewNotes, "text")}) on conflict (slug) do update set other_names = (public.crops.other_names || array(select x from unnest(excluded.other_names) as u(x) where not (x = any(public.crops.other_names))))[1:12], propagation = case when cardinality(public.crops.propagation) = 0 then excluded.propagation else public.crops.propagation end, data_status = case when ${UPGRADE} then excluded.data_status else public.crops.data_status end, summary = case when ${UPGRADE} then excluded.summary else public.crops.summary end, source_note = case when ${UPGRADE} then excluded.source_note else public.crops.source_note end, primary_method = coalesce(public.crops.primary_method, excluded.primary_method), flowering_note = coalesce(public.crops.flowering_note, excluded.flowering_note), harvest_note = coalesce(public.crops.harvest_note, excluded.harvest_note), first_yield_note = coalesce(public.crops.first_yield_note, excluded.first_yield_note), ${ESTIMATE_COLUMNS.map((col) => `${col} = case when ${UNEDITED} then excluded.${col} else public.crops.${col} end`).join(", ")};`,
  );
  const crop = `(select id from public.crops where slug = ${q(c.slug)})`;
  // Documented windows are inserted in one statement, only while the crop has
  // no documented window and no admin has edited it: re-running the seed
  // never duplicates or re-adds windows an admin changed or removed.
  const unedited = `(select updated_by from public.crops where slug = ${q(c.slug)}) is null`;
  const windowValues = (ws: typeof c.windows) =>
    ws
      .map((w, i) => `(${q(w.zone)}, ${q(w.countryCode)}, ${w.startMonth}, ${w.endMonth}, ${q(w.method)}, ${q(w.note)}, ${q(w.sourceId)}, ${q(w.sourceDetail)}, ${q(w.confidence ?? "documented")}, ${Boolean(w.optional)}, ${i})`)
      .join(", ");
  const windowInsert = (values: string, guard: string) =>
    `insert into public.crop_planting_windows (crop_id, zone, country_code, start_month, end_month, method, note, source_id, source_detail, confidence, optional, sort_order) select ${crop}, v.zone, v.country_code, v.start_month, v.end_month, v.method, v.note, v.source_id, v.source_detail, v.confidence, v.optional, v.sort_order from (values ${values}) as v(zone, country_code, start_month, end_month, method, note, source_id, source_detail, confidence, optional, sort_order) where ${guard};`;
  const documented = c.windows.filter((w) => w.confidence !== "estimated");
  if (documented.length) {
    lines.push(windowInsert(windowValues(documented), `not exists (select 1 from public.crop_planting_windows x where x.crop_id = ${crop} and x.confidence = 'documented') and ${unedited}`));
  }
  // Estimates are generated data: for crops no admin has edited they are
  // replaced on every run (delete + insert), so a re-import updates them and
  // re-running the seed never duplicates them.
  const estimated = c.windows.filter((w) => w.confidence === "estimated");
  if (c.estimate) {
    for (const table of ["crop_planting_windows", "crop_phase_windows", "crop_zone_estimates"]) {
      const scope = table === "crop_planting_windows" ? " and confidence = 'estimated'" : "";
      lines.push(`delete from public.${table} where crop_id = ${crop}${scope} and ${unedited};`);
    }
    if (estimated.length) lines.push(windowInsert(windowValues(estimated), unedited));
    if (c.phases?.length) {
      const values = c.phases
        .map((p, i) => `(${q(p.kind)}, ${q(p.zone)}, ${q(p.countryCode)}, ${p.startMonth}, ${p.endMonth}, ${Boolean(p.optional)}, ${i})`)
        .join(", ");
      lines.push(
        `insert into public.crop_phase_windows (crop_id, kind, zone, country_code, start_month, end_month, confidence, optional, sort_order) select ${crop}, v.kind, v.zone, v.country_code, v.start_month, v.end_month, 'estimated', v.optional, v.sort_order from (values ${values}) as v(kind, zone, country_code, start_month, end_month, optional, sort_order) where ${unedited};`,
      );
    }
    if (c.zoneEstimates?.length) {
      const values = c.zoneEstimates
        .map((z) => `(${q(z.zone)}, ${q(z.countryCode)}, ${q(z.suitability)}, ${q(z.irrigation)}, ${n(z.daysToFirstHarvest)}::int, ${n(z.yearsToFirstYield)}::int, ${arr(z.notApplicable, "text")})`)
        .join(", ");
      lines.push(
        `insert into public.crop_zone_estimates (crop_id, zone, country_code, suitability, irrigation, days_to_first_harvest, years_to_first_yield, not_applicable) select ${crop}, v.zone, v.country_code, v.suitability, v.irrigation, v.days, v.years, v.na from (values ${values}) as v(zone, country_code, suitability, irrigation, days, years, na) where ${unedited} on conflict (crop_id, zone, country_code) do nothing;`,
      );
    }
  }
  c.templates.forEach((t, i) => {
    lines.push(
      `insert into public.crop_task_templates (crop_id, key, type, title, description, offset_days, repeat_every_days, until_offset_days, active_months, sort_order) values (${crop}, ${q(t.key)}, ${q(t.type)}, ${q(t.title)}, ${q(t.description)}, ${t.offsetDays}, ${n(t.repeatEveryDays)}, ${n(t.untilOffsetDays)}, ${arr(t.activeMonths, "int")}, ${i}) on conflict (crop_id, key) do nothing;`,
    );
  });
  c.guide.forEach((g, i) => {
    lines.push(
      `insert into public.crop_guides (crop_id, section, title, body, sort_order) select ${crop}, ${q(g.section)}, ${q(g.title)}, ${q(g.body)}, ${i} where not exists (select 1 from public.crop_guides x where x.crop_id = ${crop} and x.section = ${q(g.section)});`,
    );
  });
  lines.push("");
}

SEED_FAQS.forEach((f, i) => {
  lines.push(
    `insert into public.faqs (question, answer, sort_order) select ${q(f.question)}, ${q(f.answer)}, ${i} where not exists (select 1 from public.faqs where question = ${q(f.question)});`,
  );
});
lines.push("");
lines.push(
  `insert into public.site_settings (key, value) values ('weather_thresholds', '${JSON.stringify(DEFAULT_THRESHOLDS)}'::jsonb) on conflict (key) do nothing;`,
);
lines.push(`insert into public.site_settings (key, value) values ('contact', '{"email": ""}'::jsonb) on conflict (key) do nothing;`);
lines.push("", "commit;", "");

const out = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(out, lines.join("\n"), "utf8");
console.log(`Wrote ${out}`);
